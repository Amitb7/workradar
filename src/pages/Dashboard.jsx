import { useEffect, useMemo, useState } from 'react';
import { Sparkles, Flame, Ban, CalendarClock, CheckCircle2, ArrowRight, RefreshCw, Target, Activity, AlertOctagon, Users } from 'lucide-react';
import { useStore } from '../lib/store.jsx';
import { activeItems, blockedPeople, rankItems, isToday } from '../lib/priority.js';
import { generateRuleSummary, generateLLMSummary } from '../lib/summary.js';
import { PEOPLE, SOURCES, ME } from '../data/mockData.js';
import { navigate } from '../lib/router.js';
import ItemCard from '../components/ItemCard.jsx';
import { Avatar, SourceIcon, Skeleton, ErrorState, EmptyState } from '../components/ui.jsx';

function greeting() {
  const h = new Date().getHours();
  return h < 12 ? 'Good morning' : h < 17 ? 'Good afternoon' : 'Good evening';
}

export default function Dashboard() {
  const { items, sync, settings, failedSources, actions } = useStore();
  const [llm, setLlm] = useState({ status: 'idle', data: null, error: null });

  const ranked = useMemo(() => rankItems(activeItems(items)), [items]);
  const blocked = useMemo(() => blockedPeople(items), [items]);
  const ruleSummary = useMemo(() => generateRuleSummary(items), [items]);
  const summary = llm.status === 'ok' ? llm.data : ruleSummary;

  // Invalidate the LLM brief when the underlying data changes.
  useEffect(() => setLlm((s) => (s.status === 'ok' ? { status: 'idle', data: null } : s)), [items]);

  const runLLM = async () => {
    setLlm({ status: 'loading' });
    try {
      const data = await generateLLMSummary(items, settings);
      setLlm({ status: 'ok', data });
    } catch (e) {
      setLlm({ status: 'error', error: e.message });
    }
  };

  if (failedSources.length === Object.keys(SOURCES).length) {
    return (
      <ErrorState
        title="We couldn't reach any of your sources"
        body="Slack, Jira, GitHub and Email all failed to sync. Your data is safe — this is usually a temporary connection or token issue."
        onRetry={() => actions.settings({ failSource: 'none' })}
      />
    );
  }

  const dueToday = ranked.filter((i) => i.dueAt && new Date(i.dueAt) - Date.now() < 12 * 3600e3).length;
  const doneToday = items.filter((i) => i.status === 'done' && isToday(i.doneAt)).length;
  const p0 = ranked.filter((i) => i.tier === 'P0').length;
  const todayBySource = Object.values(SOURCES).map((s) => ({
    ...s,
    n: items.filter((i) => i.source === s.id && isToday(i.updatedAt)).length,
  }));
  const maxN = Math.max(1, ...todayBySource.map((s) => s.n));
  const loading = sync.status === 'loading' && !sync.at;

  return (
    <div className="page">
      <div className="page-head">
        <div>
          <h1>{greeting()}, {PEOPLE[ME].name.split(' ')[0]}</h1>
          <p className="muted">
            {new Date().toLocaleDateString([], { weekday: 'long', day: 'numeric', month: 'long' })} · Here is your radar for today.
          </p>
        </div>
        <button className="btn btn-primary" onClick={() => navigate('/feed')}>
          Open priority feed <ArrowRight size={14} />
        </button>
      </div>

      <section className="card brief" aria-labelledby="brief-h">
        <div className="brief-head">
          <h2 id="brief-h"><Sparkles size={16} /> AI daily brief</h2>
          <div className="brief-tools">
            <span className="muted small">
              {summary.generatedBy === 'llm' ? 'Generated by LLM' : 'Generated by WorkRadar rules engine'} ·{' '}
              {new Date(summary.generatedAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
            </span>
            {settings.apiKey ? (
              <button className="btn btn-ghost" onClick={runLLM} disabled={llm.status === 'loading'}>
                <RefreshCw size={13} className={llm.status === 'loading' ? 'spin' : ''} /> Regenerate with AI
              </button>
            ) : (
              <a className="btn btn-ghost" href="#/settings">Connect LLM</a>
            )}
          </div>
        </div>
        {llm.status === 'error' && (
          <div className="banner banner-info small">AI brief unavailable ({llm.error}). Showing the rules-based brief instead.</div>
        )}
        {loading || llm.status === 'loading' ? (
          <Skeleton lines={4} />
        ) : (
          <>
            <p className="headline">{summary.headline}</p>
            <div className="brief-grid">
              <BriefCol icon={Target} title="Top work for today" tone="primary">
                {summary.topWork.map((t, i) => (
                  <li key={t.id}>
                    <a href={`#/item/${t.id}`}><span className="num">{i + 1}</span>{t.text}</a>
                    {t.why && <small>{t.why}</small>}
                  </li>
                ))}
              </BriefCol>
              <BriefCol icon={AlertOctagon} title="Needs immediate attention" tone="danger">
                {summary.attention.length === 0 && <li className="muted">Nothing urgent right now.</li>}
                {summary.attention.map((t) => (
                  <li key={t.id}>
                    <a href={`#/item/${t.id}`}>{t.text}</a>
                    {t.why && <small>{t.why}</small>}
                  </li>
                ))}
              </BriefCol>
              <BriefCol icon={Users} title="Who is blocked" tone="warn">
                {summary.blocked.length === 0 && <li className="muted">No one is blocked.</li>}
                {summary.blocked.map((b) => (
                  <li key={b.person + b.id}>
                    <a href={`#/item/${b.id}`} className="with-avatar"><Avatar id={b.person} size={18} />{b.text}</a>
                  </li>
                ))}
              </BriefCol>
              <BriefCol icon={Activity} title="What happened today" tone="muted">
                {summary.happened.map((h, i) => <li key={i}>{h}</li>)}
              </BriefCol>
            </div>
          </>
        )}
      </section>

      <div className="kpis">
        <Kpi icon={Flame} tone="danger" label="Need attention now" value={p0} hint="P0 items" to="/feed?tier=P0" />
        <Kpi icon={Ban} tone="warn" label="Teammates blocked" value={blocked.length} hint="waiting on someone" to="/search?q=is:blocked" />
        <Kpi icon={CalendarClock} tone="primary" label="Due today" value={dueToday} hint="within 12 hours" to="/feed" />
        <Kpi icon={CheckCircle2} tone="success" label="Completed today" value={doneToday} hint="merged / closed / done" to="/search?q=is:done" />
      </div>

      <div className="two-col">
        <section>
          <div className="section-head">
            <h2>Top priorities</h2>
            <a href="#/feed" className="link">See all {ranked.length} <ArrowRight size={13} /></a>
          </div>
          {loading ? (
            <Skeleton lines={6} />
          ) : ranked.length === 0 ? (
            <EmptyState icon={CheckCircle2} title="You're all caught up" body="Nothing needs you right now. Snoozed items will return when they're due." />
          ) : (
            <div className="stack">{ranked.slice(0, 5).map((i) => <ItemCard key={i.id} item={i} />)}</div>
          )}
        </section>

        <aside className="stack">
          <section className="card pad">
            <h3 className="card-h"><Ban size={15} /> Blocked teammates</h3>
            {blocked.length === 0 ? (
              <p className="muted small">No one is blocked right now.</p>
            ) : (
              <ul className="blocked-list">
                {blocked.map((b) => (
                  <li key={b.person}>
                    <a href={`#/item/${(b.items.find((i) => i.kind !== 'message') || b.items[0]).id}`}>
                      <Avatar id={b.person} size={30} />
                      <div>
                        <div className="strong">{PEOPLE[b.person].name}</div>
                        <div className="small muted">
                          Waiting on {b.waitingOn === ME ? 'you' : PEOPLE[b.waitingOn]?.name.split(' ')[0]} ·{' '}
                          {b.items.filter((i) => i.kind !== 'message').map((i) => i.ref).join(', ') || b.items[0].channel}
                        </div>
                      </div>
                      <span className="chip chip-danger">{Math.max(1, Math.round((Date.now() - new Date(b.since)) / 3600e3))}h</span>
                    </a>
                  </li>
                ))}
              </ul>
            )}
          </section>
          <section className="card pad">
            <h3 className="card-h"><Activity size={15} /> Activity today by source</h3>
            <ul className="bars">
              {todayBySource.map((s) => (
                <li key={s.id}>
                  <span className="bar-label"><SourceIcon source={s.id} /> {s.label}</span>
                  <span className="bar-track">
                    <span className={`bar-fill src-bg-${s.id}`} style={{ width: `${(s.n / maxN) * 100}%` }} />
                  </span>
                  <span className="bar-n">{failedSources.includes(s.id) ? '—' : s.n}</span>
                </li>
              ))}
            </ul>
          </section>
        </aside>
      </div>
    </div>
  );
}

function BriefCol({ icon: Icon, title, tone, children }) {
  return (
    <div className={`brief-col tone-${tone}`}>
      <h3><Icon size={14} /> {title}</h3>
      <ul>{children}</ul>
    </div>
  );
}

function Kpi({ icon: Icon, label, value, hint, tone, to }) {
  return (
    <a className={`card kpi tone-${tone}`} href={`#${to}`}>
      <span className="kpi-icon"><Icon size={18} /></span>
      <div>
        <div className="kpi-value">{value}</div>
        <div className="kpi-label">{label}</div>
        <div className="small muted">{hint}</div>
      </div>
    </a>
  );
}
